"""Build geometry data from the user-supplied bark reference (Pillow + numpy).

A simplified feature-mask/height-field workflow inspired by Wang et al.,
Interactive Modeling of Tree Bark. This is not their texton segmentation or
self-similarity editor, and photograph brightness is not used as depth.
"""
from pathlib import Path
import json
import math
import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
SIZE = 192
rgb = np.asarray(Image.open(ROOT / 'reference/bark/source.png').convert('RGB')
                 .resize((SIZE, SIZE)), dtype=float) / 255
# The reference's grey raised plates separate chromatically from brown furrows.
# Colour ratios reduce sensitivity to the strong illumination gradient.
mask_image = Image.fromarray(np.uint8(rgb[:, :, 1] / (rgb[:, :, 0] + .015) > .77) * 255)
mask_image = mask_image.filter(ImageFilter.MedianFilter(5)).filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.MinFilter(3))
mask = np.asarray(mask_image) > 127

def distance_inside(region):
    distance = np.where(region, 1000., 0.)
    for ys, xs in [(range(SIZE), range(SIZE)), (range(SIZE-1, -1, -1), range(SIZE-1, -1, -1))]:
        direction = 1 if ys.start == 0 else -1
        for y in ys:
            for x in xs:
                for dx, dy in [(-direction, 0), (0, -direction), (-direction, -direction), (direction, -direction)]:
                    xx, yy = x + dx, y + dy
                    if 0 <= xx < SIZE and 0 <= yy < SIZE:
                        distance[y, x] = min(distance[y, x], distance[yy, xx] + math.hypot(dx, dy))
    return distance

ridge = distance_inside(mask)
furrow = distance_inside(~mask)
# Broad raised plates and deep recessed furrows, with rounded feature shoulders.
height = np.where(mask, .38 + .62 * (1 - np.exp(-ridge / 3.2)), .18 * np.exp(-furrow / 2.3))
height = Image.fromarray(np.uint8(height * 255)).filter(ImageFilter.GaussianBlur(1.4))
data = {'size': SIZE, 'values': np.asarray(height).ravel().tolist()}
(ROOT / 'src/BarkHeightData.js').write_text('// Generated by tools/build_bark_height.py from reference/bark/source.png.\nexport default ' + json.dumps(data, separators=(',', ':')) + ';\n')
